import path from 'node:path';
import ts from 'typescript';
import { listFiles, type ProjectTarget, type WorkspaceDiagnostic } from './workspace.js';

export const DEFAULT_COMPILER_OPTIONS: ts.CompilerOptions = {
  target: ts.ScriptTarget.ES2022,
  module: ts.ModuleKind.ESNext,
  moduleResolution: ts.ModuleResolutionKind.Bundler,
  experimentalDecorators: true,
  strict: true,
  lib: ['lib.es2023.d.ts', 'lib.dom.d.ts', 'lib.dom.iterable.d.ts'],
};

/** Options that keep program creation side-effect free and cheap. */
const FORCED: ts.CompilerOptions = {
  noEmit: true,
  skipLibCheck: true,
  incremental: false,
  composite: false,
  declaration: false,
  sourceMap: false,
  plugins: [],
};

function parseTsconfig(file: string, diagnostics: WorkspaceDiagnostic[], seen = new Set<string>()): { fileNames: string[]; options: ts.CompilerOptions } {
  seen.add(file);
  let fatal: ts.Diagnostic | undefined;
  const parsed = ts.getParsedCommandLineOfConfigFile(file, {}, {
    ...ts.sys,
    onUnRecoverableConfigFileDiagnostic: (d) => { fatal = d; },
  });
  if (!parsed || fatal) {
    diagnostics.push({
      code: 'tsconfig-invalid',
      level: 'warning',
      message: `cannot parse ${file}: ${fatal ? ts.flattenDiagnosticMessageText(fatal.messageText, ' ') : 'unknown error'}; using default compiler options`,
      file,
    });
    return { fileNames: listFiles(path.dirname(file), isSourceTs), options: DEFAULT_COMPILER_OPTIONS };
  }
  let fileNames = parsed.fileNames;
  // Solution-style tsconfig (`files: []` + references), as generated by the Angular CLI.
  if (!fileNames.length && parsed.projectReferences?.length) {
    for (const ref of parsed.projectReferences) {
      const refFile = ts.resolveProjectReferencePath(ref);
      if (seen.has(refFile) || /spec/i.test(path.basename(refFile))) continue;
      fileNames = fileNames.concat(parseTsconfig(refFile, diagnostics, seen).fileNames);
    }
  }
  return { fileNames, options: parsed.options };
}

const isSourceTs = (f: string) => f.endsWith('.ts') && !f.endsWith('.d.ts');

/** Root files and compiler options for a project (no program is built). */
export function resolveProjectFiles(target: ProjectTarget, diagnostics: WorkspaceDiagnostic[]): { fileNames: string[]; options: ts.CompilerOptions } {
  if (target.tsconfig) return parseTsconfig(target.tsconfig, diagnostics);
  return { fileNames: listFiles(target.sourceRoot, isSourceTs), options: DEFAULT_COMPILER_OPTIONS };
}

export function createProjectProgram(target: ProjectTarget, diagnostics: WorkspaceDiagnostic[]): ts.Program {
  const { fileNames, options } = resolveProjectFiles(target, diagnostics);
  const finalOptions = { ...options, ...FORCED };
  return ts.createProgram({ rootNames: fileNames, options: finalOptions, host: ts.createCompilerHost(finalOptions, true) });
}

/**
 * Builds a program over in-memory files (used by tests, the playground generator
 * and future editor integrations). Library `.d.ts` files come from the bundled TypeScript.
 */
export function createInMemoryProgram(files: Record<string, string>, root: string, options: ts.CompilerOptions = DEFAULT_COMPILER_OPTIONS): ts.Program {
  const finalOptions = { ...options, ...FORCED };
  const abs = new Map(Object.entries(files).map(([name, text]) => [path.resolve(root, name), text]));
  const host = ts.createCompilerHost(finalOptions, true);
  const getSourceFile = host.getSourceFile.bind(host);
  host.getSourceFile = (fileName, langVersion, onError, shouldCreate) => {
    const text = abs.get(path.resolve(fileName));
    if (text !== undefined) return ts.createSourceFile(fileName, text, langVersion, true);
    return getSourceFile(fileName, langVersion, onError, shouldCreate);
  };
  const fileExists = host.fileExists.bind(host);
  host.fileExists = (f) => abs.has(path.resolve(f)) || fileExists(f);
  const dirs = new Set([...abs.keys()].flatMap((f) => {
    const out: string[] = [];
    for (let d = path.dirname(f); d !== path.dirname(d); d = path.dirname(d)) out.push(d);
    return out;
  }));
  const directoryExists = host.directoryExists?.bind(host);
  host.directoryExists = (d) => dirs.has(path.resolve(d)) || (directoryExists ? directoryExists(d) : false);
  const readFile = host.readFile.bind(host);
  host.readFile = (f) => abs.get(path.resolve(f)) ?? readFile(f);
  return ts.createProgram({ rootNames: [...abs.keys()].filter((f) => f.endsWith('.ts')), options: finalOptions, host });
}
